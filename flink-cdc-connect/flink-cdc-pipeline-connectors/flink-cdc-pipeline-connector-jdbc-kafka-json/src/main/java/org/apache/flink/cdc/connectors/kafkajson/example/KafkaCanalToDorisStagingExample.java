/**
 * Self-contained DataStream job that dumps the canal-flatMessage stream of a Kafka topic from the
 * very beginning into a Doris staging ("temporary") table: every Kafka message that passes the
 * configured table filter becomes one row, carrying a sink-generated auto-increment id, the
 * ingest/event timestamps, the Kafka coordinates (topic / partition / offset) and the raw
 * canal-json string.
 *
 * <h2>Scope: single tables, whole databases, everything</h2>
 *
 * <p>{@code --table-filter} decides what lands in the staging table: {@code db.table} keeps one
 * exact table, {@code db.*} keeps <b>every table of one database</b> (whole-database sync), and
 * {@code *} (or omitting the option) keeps everything the topic carries. Entries combine freely,
 * comma-separated. All of it goes into the single target table — the {@code canal_database} and
 * {@code canal_table} columns tell the rows apart, and {@code canal_json} still carries each
 * message verbatim.
 *
 * <h2>Topology</h2>
 *
 * <pre>{@code
 * StartupOffsetKafkaSource           CanalTableFilterFunction              DorisStagingSink
 * (assign + seek to startup)  -->    (parse canal-json,           -->      (buffer + StreamLoad
 *                                      keep only the selected              into the staging table)
 *                                      db/table(s))
 * }</pre>
 *
 * <p>Unlike {@code DorisSinkExample} (the test-sources assembly of the full connector stack —
 * source factory, schema operator, partitioning chain, {@code KafkaJsonDataSinkBuilder}) — this
 * job is the minimal
 * custom-assembly path: it reuses the connector's {@link CanalMessageParser} to deserialize the
 * raw Kafka value into a {@link CanalMessage} and the connector's {@link DorisHttpClient} for the
 * Doris Stream Load / DDL HTTP calls, and keeps everything else (offset handling, filtering,
 * batching) hand-written and inspectable.
 *
 * <h2>The staging table</h2>
 *
 * <pre>{@code
 * CREATE TABLE IF NOT EXISTS {database}.{table} (
 *     id              BIGINT  NOT NULL,          -- generated by the sink (AtomicLong)
 *     kafka_topic     VARCHAR(255) NOT NULL,
 *     kafka_partition INT         NOT NULL,
 *     kafka_offset    BIGINT      NOT NULL,
 *     canal_database  VARCHAR(255),
 *     canal_table     VARCHAR(255),
 *     canal_type      VARCHAR(32),
 *     canal_is_ddl    BOOLEAN,
 *     canal_row_count INT,
 *     canal_es        BIGINT,   -- binlog execution time (epoch millis)
 *     canal_ts        BIGINT,   -- time canal sent the message (epoch millis)
 *     ingest_ts       BIGINT,   -- time this row was built (epoch millis)
 *     canal_json      STRING    -- the raw canal-json kafka message
 * ) UNIQUE KEY(id) DISTRIBUTED BY HASH(id) BUCKETS AUTO ...
 * }</pre>
 *
 * <p>The {@code id} column is generated by the sink itself — an {@link AtomicLong} per subtask,
 * so no Doris version feature is involved: the counter is seeded with a time-based value ({@code
 * currentTimeMillis() * 1000} plus the subtask index) and advances by the sink parallelism, so
 * the subtasks' id sequences never overlap, and a restart re-seeds from a later clock reading so
 * new ids are always larger than everything written before the restart (with UNIQUE KEY(id), an
 * id that collides would overwrite a history row instead of appending one). The UNIQUE model
 * stays: it accepts the {@code __DORIS_DELETE_SIGN__} hidden column the {@link
 * DorisHttpClient#streamLoad} protocol always declares, and the id key keeps the table
 * point-queryable.
 *
 * <h2>Consumption and delivery semantics</h2>
 *
 * <ul>
 *   <li>The source manually {@code assign}s every partition of the topic and seeks it to the
 *       configured startup position — {@code --startup-mode earliest} (the default) seeks to the
 *       very beginning, {@code --startup-mode latest} seeks to the current end so only messages
 *       that arrive after the job starts are consumed, and {@code --startup-mode timestamp}
 *       seeks to the first message whose Kafka timestamp is at or after {@code
 *       --startup-timestamp}. The timestamp's digit count selects the unit: 10 digits are epoch
 *       seconds, 13 digits are epoch milliseconds (Kafka's native unit). Either way no
 *       consumer-group offset is ever consulted. The source keeps no offsets in Flink state,
 *       therefore a restart seeks to the startup position again: a restart in {@code earliest}
 *       or {@code timestamp} mode replays from there (duplicates, see below), while a restart in
 *   {@code latest} mode <b>skips</b> everything that arrived while the job was down — pick the
 *       mode that matches how the staging table is used.
 *   <li>With {@code --stop-at-latest} the job is bounded: it stops after every partition has
 *       reached the end offset that was current at startup — a one-shot dump of the topic's
 *       history. Without it the job keeps consuming new messages. Note that combining it with
 *   {@code --startup-mode latest} yields an empty dump: start and end coincide.
 *   <li>Delivery is at-least-once: buffers are flushed on every checkpoint and before close. A
 *       replayed batch is normally absorbed by the StreamLoad label (the label names the first and
 *       last Kafka coordinates of the batch, so the same range replayed after a restart reuses the
 *       label and Doris answers "Label Already Exists / FINISHED", which counts as committed), but
 *       batches that split differently after a restart do produce duplicate rows under fresh ids.
 *   <li>For a repeatable one-shot dump, run with {@code --rebuild --stop-at-latest}: the staging
 *       table is dropped and recreated before the job starts, so every run leaves exactly the
 *       topic's current content.
 * </ul>
 *
 * <h2>Prerequisites</h2>
 *
 * <ul>
 *   <li>Canal writes <b>flatMessage</b> JSON to the topic ({@code canal.mq.flatMessage=true}); DDL
 *       and DML messages both carry {@code database}/{@code table} and both pass the filter.
 *   <li>The Doris FE option {@code is_execute_sql_in_http=true} is required for the query endpoint
 *       this job uses for its DDL (the same requirement the connector's schema evolution has).
 * </ul>
 *
 * <h2>Usage</h2>
 *
 * <pre>{@code
 * flink run flink-cdc-pipeline-connector-jdbc-kafka-json.jar \
 *     org.apache.flink.cdc.connectors.kafkajson.example.KafkaCanalToDorisStagingExample \
 *     --kafka-bootstrap-servers=broker1:9092 \
 *     --kafka-topic=canal-json-topic \
 *     --table-filter=db1.orders,db2.customers \
 *     --startup-mode=earliest \
 *     --doris-fenodes=fe1:8030 \
 *     --doris-username=root \
 *     --doris-password=secret \
 *     --doris-database=staging \
 *     --rebuild --stop-at-latest
 * }</pre>
 *
 * <p>Use {@code --table-filter db1.*} to stage a whole database in one table, and omit the option
 * to stage everything the topic carries. Use {@code --startup-mode latest} to consume only
 * messages that arrive from now on (no history replay), or {@code --startup-mode timestamp
 * --startup-timestamp 1700000000} (seconds) / {@code 1700000000000} (millis) to replay from a
 * given moment.
 *
 * <p>Run {@code --help} for the full option list.
 */
