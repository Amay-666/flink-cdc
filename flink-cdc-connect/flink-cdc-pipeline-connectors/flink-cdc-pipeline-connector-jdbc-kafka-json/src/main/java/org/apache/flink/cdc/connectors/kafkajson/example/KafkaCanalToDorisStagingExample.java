    private static final Logger LOG =
            LoggerFactory.getLogger(KafkaCanalToDorisStagingExample.class);

    /** Default name of the Doris staging table created by this example. */
    static final String DEFAULT_DORIS_TABLE = "canal_json_staging";

    static final String DEFAULT_DORIS_USERNAME = "root";
    static final String DEFAULT_KAFKA_GROUP_ID = "canal-doris-staging";
    static final int DEFAULT_BATCH_SIZE = 500;
    static final long DEFAULT_FLUSH_INTERVAL_MS = 3_000L;
    static final String DEFAULT_DORIS_REPLICATION_ALLOCATION = "tag.location.group_a: 3";

    /** Doris StreamLoad / DDL retries, matching the connector's sink default. */
    static final int DORIS_MAX_RETRIES = 3;

    /**
     * The database every existing Doris installation carries; it is the context the {@code CREATE
     * DATABASE} statement runs in, because the query endpoint URL embeds a database that must
     * already exist — the target database itself does not exist yet at that point.
     */
    static final String DORIS_SYSTEM_DATABASE = "information_schema";

    // ─────────────────────── staging table columns ───────────────────────

    static final String COL_ID = "id";
    static final String COL_KAFKA_TOPIC = "kafka_topic";
    static final String COL_KAFKA_PARTITION = "kafka_partition";
    static final String COL_KAFKA_OFFSET = "kafka_offset";
    static final String COL_CANAL_DATABASE = "canal_database";
    static final String COL_CANAL_TABLE = "canal_table";
    static final String COL_CANAL_TYPE = "canal_type";
    static final String COL_CANAL_IS_DDL = "canal_is_ddl";
    static final String COL_CANAL_ROW_COUNT = "canal_row_count";
    static final String COL_CANAL_ES = "canal_es";
    static final String COL_CANAL_TS = "canal_ts";
    static final String COL_INGEST_TS = "ingest_ts";
    static final String COL_CANAL_JSON = "canal_json";

    public static void main(String[] args) throws Exception {
        Params params = Params.parseOrExit(args);

        // Create (or recreate) the staging table before submitting the job: DDL once, on the
        // client, not per sink subtask — CREATE/DROP are not safe to run concurrently.
        createStagingTable(params);

        StreamExecutionEnvironment env = StreamExecutionEnvironment.getExecutionEnvironment();
        env.setParallelism(1);
        // At-least-once: the sink drains its buffer on every checkpoint barrier, so no buffered
        // row is ever lost on a failure. Bounded one-shot dumps do not need it but are not harmed.
        env.enableCheckpointing(30_000L);

        DataStream<StagedCanalRow> matched =
                env.addSource(
                                new StartupOffsetKafkaSource(
                                        params.kafkaBootstrapServers,
                                        params.kafkaTopic,
                                        params.kafkaGroupId,
                                        params.startupMode,
                                        params.startupTimestampMillis,
                                        params.stopAtLatest))
                        .name("kafka-startup-offsets")
                        .uid("kafka-startup-offsets")
                        .flatMap(new CanalTableFilterFunction(params.tableFilter))
                        .name("parse-canal-and-filter-table")
                        .uid("parse-canal-and-filter-table");

        matched.addSink(
                        new DorisStagingSink(
                                params.dorisFenodes,
                                params.dorisUsername,
                                params.dorisPassword,
                                params.dorisDatabase,
                                params.dorisTable,
                                params.batchSize,
                                params.flushIntervalMs))
                .name("doris-staging-sink")
                .uid("doris-staging-sink");

        env.execute("kafka-canal-json-to-doris-staging");
    }

    // ─────────────────────── staging table DDL ───────────────────────

    /**
     * Creates the target database and the staging table over the Doris query endpoint. With {@code
     * rebuild} the table is dropped first, so a rerun of a one-shot dump starts from an empty
     * table instead of appending a second copy of the topic under fresh auto-increment ids.
     */
    private static void createStagingTable(Params params) throws IOException {
        try (DorisHttpClient client =
                new DorisHttpClient(
                        params.dorisFenodes,
                        params.dorisUsername,
                        params.dorisPassword,
                        DORIS_MAX_RETRIES)) {
            // CREATE DATABASE runs in the context of a database that always exists (the URL of the
            // query endpoint embeds one); CREATE/DROP TABLE run in the target database.
            client.executeSql(
                    DORIS_SYSTEM_DATABASE,
                    "CREATE DATABASE IF NOT EXISTS " + quote(params.dorisDatabase));
            if (params.rebuild) {
                client.executeSql(
                        params.dorisDatabase,
                        "DROP TABLE IF EXISTS "
                                + quote(params.dorisDatabase)
                                + "."
                                + quote(params.dorisTable));
            }
            client.executeSql(params.dorisDatabase, buildCreateTableSql(params));
        }
        LOG.info(
                "Staging table {}.{} is ready (rebuild={})",
                params.dorisDatabase,
                params.dorisTable,
                params.rebuild);
    }

    /** Builds the {@code CREATE TABLE IF NOT EXISTS} statement for the staging table. */
    static String buildCreateTableSql(Params params) {
        return "CREATE TABLE IF NOT EXISTS "
                + quote(params.dorisDatabase)
                + "."
                + quote(params.dorisTable)
                + " ("
                + quote(COL_ID)
                + " BIGINT NOT NULL COMMENT 'row id generated by the sink: AtomicLong, monotonic"
                + " per subtask, time-based base', "
                + quote(COL_KAFKA_TOPIC)
                + " VARCHAR(255) NOT NULL COMMENT 'kafka topic the message was consumed from', "
                + quote(COL_KAFKA_PARTITION)
                + " INT NOT NULL COMMENT 'kafka partition of the message', "
                + quote(COL_KAFKA_OFFSET)
                + " BIGINT NOT NULL COMMENT 'kafka offset of the message', "
                + quote(COL_CANAL_DATABASE)
                + " VARCHAR(255) COMMENT 'database carried by the canal message', "
                + quote(COL_CANAL_TABLE)
                + " VARCHAR(255) COMMENT 'table carried by the canal message', "
                + quote(COL_CANAL_TYPE)
                + " VARCHAR(32) COMMENT 'canal event type: INSERT/UPDATE/DELETE/CREATE/ALTER/...', "
                + quote(COL_CANAL_IS_DDL)
                + " BOOLEAN COMMENT 'whether the canal message is a DDL', "
                + quote(COL_CANAL_ROW_COUNT)
                + " INT COMMENT 'row count of the canal message data array', "
                + quote(COL_CANAL_ES)
                + " BIGINT COMMENT 'binlog execution time, epoch millis', "
                + quote(COL_CANAL_TS)
                + " BIGINT COMMENT 'time canal sent the message, epoch millis', "
                + quote(COL_INGEST_TS)
                + " BIGINT COMMENT 'time this row was built, epoch millis', "
                + quote(COL_CANAL_JSON)
                + " STRING COMMENT 'raw canal-json string of the kafka message'"
                + ") UNIQUE KEY("
                + quote(COL_ID)
                + ") COMMENT 'staging table for canal-json kafka messages'"
                + " DISTRIBUTED BY HASH("
                + quote(COL_ID)
                + ") BUCKETS AUTO"
                + " PROPERTIES (\"replication_allocation\" = \""
                + params.dorisReplicationAllocation
                + "\")";
    }

    private static String quote(String identifier) {
        return "`" + identifier.replace("`", "``") + "`";
    }

    // ─────────────────────── kafka source ───────────────────────

    /**
     * Where the source starts consuming, the {@code --startup-mode} option: {@code earliest}
     * (default) replays the topic from the very beginning, {@code latest} consumes only messages
     * that arrive after the job starts, {@code timestamp} starts at the first message whose Kafka
     * timestamp is at or after {@code --startup-timestamp} (10 digits = epoch seconds, 13 digits =
     * epoch milliseconds). Values named after Kafka's own {@code auto.offset.reset}.
     */
    public enum StartupMode {
        EARLIEST,
        LATEST,
        TIMESTAMP
    }

    /**
     * One raw Kafka record: the value string plus its Kafka coordinates, so downstream operators
     * (and the staging table) can attribute each row to its exact position in the topic.
     */
    public static class RawKafkaRecord {
        public String topic;
        public int partition;
        public long offset;
        public String value;

        public RawKafkaRecord() {}

        public RawKafkaRecord(String topic, int partition, long offset, String value) {
            this.topic = topic;
            this.partition = partition;
            this.offset = offset;
            this.value = value;
        }
    }

    /**
     * Consumes the topic from the configured {@link StartupMode} position, on every (re)start.
     *
     * <p>All partitions are listed, {@code assign}ed and seeked manually — no consumer-group
     * subscription, no committed offsets, no {@code auto.offset.reset} involved: the startup
     * position never depends on any external group state. Offsets are not kept in Flink state
     * either, so a recovery seeks to the startup position again: {@code earliest} replays the
     * whole topic (duplicates in the staging table, absorbed in part by the StreamLoad labels),
     * {@code latest} skips whatever arrived while the job was down, and {@code timestamp} replays
     * from the given timestamp again. See the class javadoc for the interplay with the staging
     * table.
     *
     * <p>The timestamp mode locates, per partition, the first message whose <b>Kafka message
     * timestamp</b> (canal's CreateTime — when canal sent the message, roughly the binlog event
     * time, not exactly the canal {@code es} field) is at or after the given epoch millis; a
     * partition whose newest message is older than that starts waiting at its end (like {@code
     * latest}).
     *
     * <p>With {@code stopAtLatest} the source is bounded: the end offsets are snapshotted once at
     * startup and the source stops after every partition has been consumed up to its snapshot —
     * a one-shot dump that leaves exactly the messages the topic held when the job started. (In
     * {@code latest} mode start and end coincide, so the dump is empty — the combination is
     * accepted but pointless, and a warning is logged.)
     */
    public static class StartupOffsetKafkaSource extends RichSourceFunction<RawKafkaRecord> {

        private static final long serialVersionUID = 1L;

        private static final Duration POLL_TIMEOUT = Duration.ofMillis(500L);

        private final String bootstrapServers;
        private final String topic;
        private final String groupId;
        private final StartupMode startupMode;
        /** Epoch millis; only consulted in {@link StartupMode#TIMESTAMP} mode. */
        private final long startupTimestampMillis;
        private final boolean stopAtLatest;

        private volatile boolean running = true;
        private transient KafkaConsumer<String, String> consumer;

        public StartupOffsetKafkaSource(
                String bootstrapServers,
                String topic,
                String groupId,
                StartupMode startupMode,
                long startupTimestampMillis,
                boolean stopAtLatest) {
            this.bootstrapServers = bootstrapServers;
            this.topic = topic;
            this.groupId = groupId;
            this.startupMode = startupMode;
            this.startupTimestampMillis = startupTimestampMillis;
            this.stopAtLatest = stopAtLatest;
        }

        @Override
        public void open(Configuration parameters) {
            Properties props = new Properties();
            props.setProperty(ConsumerConfig.BOOTSTRAP_SERVERS_CONFIG, bootstrapServers);
            // Required by the client even though this source never subscribes through the group
            // protocol (assign/seek are manual), so no rebalance ever moves our partitions.
            props.setProperty(ConsumerConfig.GROUP_ID_CONFIG, groupId);
            props.setProperty(
                    ConsumerConfig.KEY_DESERIALIZER_CLASS_CONFIG,
                    StringDeserializer.class.getName());
            props.setProperty(
                    ConsumerConfig.VALUE_DESERIALIZER_CLASS_CONFIG,
                    StringDeserializer.class.getName());
            props.setProperty(ConsumerConfig.ALLOW_AUTO_CREATE_TOPICS_CONFIG, "false");
            this.consumer = new KafkaConsumer<>(props);
        }

        @Override
        public void run(SourceFunction.SourceContext<RawKafkaRecord> ctx) throws Exception {
            List<TopicPartition> partitions = listPartitions();
            LOG.info(
                    "Consuming topic {} from {} across {} partition(s){}",
                    topic,
                    startupMode == StartupMode.TIMESTAMP
                            ? startupMode + "@" + startupTimestampMillis
                            : startupMode,
                    partitions.size(),
                    stopAtLatest ? " (bounded: stops at the current end offsets)" : "");
            consumer.assign(partitions);
            switch (startupMode) {
                case EARLIEST:
                    consumer.seekToBeginning(partitions);
                    break;
                case LATEST:
                    consumer.seekToEnd(partitions);
                    break;
                case TIMESTAMP:
                    seekToTimestamp(partitions, startupTimestampMillis);
                    break;
            }
            if (stopAtLatest && startupMode == StartupMode.LATEST) {
                LOG.warn(
                        "--stop-at-latest together with --startup-mode=latest: the end offsets"
                                + " equal the startup position, the job stops without consuming"
                                + " anything.");
            }
            Map<TopicPartition, Long> endOffsets =
                    stopAtLatest ? consumer.endOffsets(partitions) : null;
            Set<TopicPartition> caughtUp = new HashSet<>();

            while (running) {
                ConsumerRecords<String, String> records;
                try {
                    records = consumer.poll(POLL_TIMEOUT);
                } catch (WakeupException e) {
                    // cancel() woke the poll; leave without emitting anything further.
                    break;
                }
                for (ConsumerRecord<String, String> record : records) {
                    // The checkpoint lock keeps emissions and the source's progress consistent
                    // with the checkpoint: everything emitted before a barrier belongs to it.
                    synchronized (ctx.getCheckpointLock()) {
                        ctx.collect(
                                new RawKafkaRecord(
                                        record.topic(),
                                        record.partition(),
                                        record.offset(),
                                        record.value()));
                    }
                }
                if (stopAtLatest) {
                    boolean done;
                    try {
                        done = allCaughtUp(partitions, endOffsets, caughtUp);
                    } catch (WakeupException e) {
                        // cancel() raced this position() call; stop like the poll above does.
                        break;
                    }
                    if (done) {
                        LOG.info(
                                "Every partition of {} reached its startup end offset; source"
                                        + " stops.",
                                topic);
                        break;
                    }
                }
            }
        }

        private List<TopicPartition> listPartitions() {
            List<PartitionInfo> infos = consumer.partitionsFor(topic);
            if (infos == null || infos.isEmpty()) {
                throw new IllegalStateException(
                        "Topic "
                                + topic
                                + " returned no partitions from "
                                + bootstrapServers
                                + "; check the topic name and the bootstrap servers.");
            }
            List<TopicPartition> partitions = new ArrayList<>(infos.size());
            for (PartitionInfo info : infos) {
                partitions.add(new TopicPartition(topic, info.partition()));
            }
            return partitions;
        }

        /**
         * Seeks every partition to its first message whose Kafka timestamp is at or after the
         * given epoch millis ({@code offsetsForTimes} semantics). A partition whose newest message
         * is older than the timestamp has no such position — Kafka returns {@code null} — and
         * starts waiting at its end instead, exactly like {@code latest} would.
         */
        private void seekToTimestamp(List<TopicPartition> partitions, long timestampMillis) {
            Map<TopicPartition, Long> timestamps = new HashMap<>();
            for (TopicPartition partition : partitions) {
                timestamps.put(partition, timestampMillis);
            }
            Map<TopicPartition, OffsetAndTimestamp> located = consumer.offsetsForTimes(timestamps);
            List<TopicPartition> olderThanTimestamp = new ArrayList<>();
            for (TopicPartition partition : partitions) {
                OffsetAndTimestamp offsetAndTimestamp = located.get(partition);
                if (offsetAndTimestamp == null) {
                    olderThanTimestamp.add(partition);
                } else {
                    LOG.info(
                            "Partition {} starts at offset {} (first message at/after {})",
                            partition,
                            offsetAndTimestamp.offset(),
                            timestampMillis);
                    consumer.seek(partition, offsetAndTimestamp.offset());
                }
            }
            if (!olderThanTimestamp.isEmpty()) {
                LOG.info(
                        "Partitions {} have no message at/after {}; starting at their end",
                        olderThanTimestamp,
                        timestampMillis);
                consumer.seekToEnd(olderThanTimestamp);
            }
        }

        /**
         * Marks partitions whose position has reached their startup end offset, and returns
         * whether every partition has. {@code position()} is a local lookup on the assigned
         * consumer, so calling it after every poll is cheap.
         */
        private boolean allCaughtUp(
                List<TopicPartition> partitions,
                Map<TopicPartition, Long> endOffsets,
                Set<TopicPartition> caughtUp) {
            for (TopicPartition partition : partitions) {
                if (caughtUp.contains(partition)) {
                    continue;
                }
                if (consumer.position(partition) >= endOffsets.get(partition)) {
                    caughtUp.add(partition);
                }
            }
            return caughtUp.containsAll(partitions);
        }

        @Override
        public void cancel() {
            running = false;
            KafkaConsumer<String, String> c = this.consumer;
            if (c != null) {
                // poll() is the only call that blocks; wake it so run() observes `running`.
                c.wakeup();
            }
        }

        @Override
        public void close() {
            if (consumer != null) {
                consumer.close();
            }
        }
    }

    // ─────────────────────── parse + filter ───────────────────────

    /**
     * The table selection of {@code --table-filter}: one or more comma-separated entries of
     *
     * <ul>
     *   <li>{@code db.table} — one exact table
     *   <li>{@code db.*} — <b>every table of one database</b> (whole-database sync)
     *   <li>{@code *} (or {@code *.*}) — everything the topic carries
     * </ul>
     *
     * <p>Matches are exact and case-sensitive on the {@code database}/{@code table} fields the
     * canal message carries (canal writes them exactly as the source database does). {@code
     * Serializable} so it can travel into the operator with the function.
     */
    public static final class TableFilter implements Serializable {

        private static final long serialVersionUID = 1L;

        private final Set<String> exactTables;
        private final Set<String> wholeDatabases;
        private final boolean everything;

        private TableFilter(
                Set<String> exactTables, Set<String> wholeDatabases, boolean everything) {
            this.exactTables = exactTables;
            this.wholeDatabases = wholeDatabases;
            this.everything = everything;
        }

        /**
         * Parses the comma-separated {@code --table-filter} spec. A blank spec — the option not
         * given at all — means "everything".
         *
         * @throws IllegalArgumentException on an entry that is neither {@code db.table}, {@code
         *     db.*} nor {@code *}
         */
        static TableFilter parse(String spec) {
            Set<String> exactTables = new HashSet<>();
            Set<String> wholeDatabases = new HashSet<>();
            boolean everything = false;
            boolean anyEntry = false;
            if (spec != null && !spec.trim().isEmpty()) {
                for (String entry : spec.split(",")) {
                    String trimmed = entry.trim();
                    if (trimmed.isEmpty()) {
                        continue;
                    }
                    anyEntry = true;
                    if ("*".equals(trimmed) || "*.*".equals(trimmed)) {
                        everything = true;
                    } else if (trimmed.endsWith(".*")) {
                        wholeDatabases.add(trimmed.substring(0, trimmed.length() - 2));
                    } else if (trimmed.indexOf('.') > 0) {
                        exactTables.add(trimmed);
                    } else {
                        throw new IllegalArgumentException(
                                "--table-filter entries must be <database>.<table>,"
                                        + " <database>.* or *, got: '"
                                        + trimmed
                                        + "'");
                    }
                }
            }
            if (!anyEntry) {
                everything = true;
            }
            return new TableFilter(exactTables, wholeDatabases, everything);
        }

        /** Whether the message of this database/table passes the filter. */
        boolean matches(String database, String table) {
            if (database == null || table == null) {
                return false;
            }
            if (everything) {
                return true;
            }
            if (exactTables.contains(database + "." + table)) {
                return true;
            }
            return wholeDatabases.contains(database);
        }
    }

    /** One staging-table row's source material: Kafka coordinates + the parsed canal message. */
    public static class StagedCanalRow {
        public String kafkaTopic;
        public int kafkaPartition;
        public long kafkaOffset;
        public String canalDatabase;
        public String canalTable;
        public String canalType;
        public boolean canalIsDdl;
        public int canalRowCount;
        public long canalEs;
        public long canalTs;
        public long ingestTimestamp;
        public String canalJson;

        public StagedCanalRow() {}

        public StagedCanalRow(RawKafkaRecord record, CanalMessage message, long ingestTimestamp) {
            this.kafkaTopic = record.topic;
            this.kafkaPartition = record.partition;
            this.kafkaOffset = record.offset;
            this.canalDatabase = message.getDatabase();
            this.canalTable = message.getTable();
            this.canalType = message.getType();
            this.canalIsDdl = message.isDdl();
            this.canalRowCount = message.getData() == null ? 0 : message.getData().size();
            this.canalEs = message.getEs();
            this.canalTs = message.getTs();
            this.ingestTimestamp = ingestTimestamp;
            this.canalJson = record.value;
        }
    }

    /**
     * Parses each raw record with the connector's {@link CanalMessageParser} and emits one {@link
     * StagedCanalRow} per record the {@link TableFilter} selects — an exact {@code db.table}, a
     * whole database ({@code db.*}) or everything ({@code *}).
     *
     * <p>Parsing is lenient on purpose: a canal topic can carry records the flatMessage parser
     * cannot read (broker tombstones, heartbeats, a different serializer left on the topic). Those
     * are counted and skipped instead of failing the job — a dump must not die on one bad record.
     * Messages the filter does not select are dropped silently (counted in the close() summary).
     */
    public static class CanalTableFilterFunction
            extends RichFlatMapFunction<RawKafkaRecord, StagedCanalRow> {

        private static final long serialVersionUID = 1L;

        /** Records whose parse failures are logged every this many occurrences. */
        private static final long PARSE_FAILURE_LOG_INTERVAL = 100L;

        private final TableFilter tableFilter;

        private transient CanalMessageParser parser;
        private transient long unparsableRecords;
        private transient long otherTableRecords;
        private transient long matchedRecords;

        public CanalTableFilterFunction(TableFilter tableFilter) {
            this.tableFilter = tableFilter;
        }

        @Override
        public void open(Configuration parameters) {
            // Not serializable (and cheap to build): recreate per subtask.
            this.parser = new CanalMessageParser();
            this.unparsableRecords = 0L;
            this.otherTableRecords = 0L;
            this.matchedRecords = 0L;
        }

        @Override
        public void flatMap(RawKafkaRecord record, Collector<StagedCanalRow> out) {
            CanalMessage message;
            try {
                message = parser.parse(record.value);
            } catch (RuntimeException e) {
                unparsableRecords++;
                if (unparsableRecords % PARSE_FAILURE_LOG_INTERVAL == 1L) {
                    LOG.warn(
                            "Record {}:{}:{} is not a canal flatMessage ({} so far); first error:"
                                    + " {}",
                            record.topic,
                            record.partition,
                            record.offset,
                            unparsableRecords,
                            abbreviate(e.getMessage()));
                }
                return;
            }
            if (message == null) {
                // blank payload — nothing to stage
                unparsableRecords++;
                return;
            }
            if (!tableFilter.matches(message.getDatabase(), message.getTable())) {
                otherTableRecords++;
                return;
            }
            matchedRecords++;
            out.collect(new StagedCanalRow(record, message, System.currentTimeMillis()));
        }

        /**
         * Truncates a parse error message: the parser reports the offending json in it, and a full
         * canal message can be huge.
         */
        private static String abbreviate(String message) {
            if (message == null) {
                return "null";
            }
            return message.length() <= 200 ? message : message.substring(0, 200) + "...";
        }

        @Override
        public void close() {
            LOG.info(
                    "Canal parse/filter summary: {} matched, {} other-table, {} unparsable",
                    matchedRecords,
                    otherTableRecords,
                    unparsableRecords);
        }
    }

    // ─────────────────────── doris sink ───────────────────────

    /**
     * Buffers {@link StagedCanalRow}s and writes them to the Doris staging table via {@link
     * DorisHttpClient#streamLoad} in JSON batches.
     *
     * <p>A flush is triggered by the row threshold ({@code --batch-size}), the time threshold
     * ({@code --flush-interval-ms}, checked on arrival so an idle stream never flushes half-empty
     * batches), every checkpoint barrier (the buffer must be empty when the barrier passes,
     * otherwise a recovery would lose the buffered rows — this is what makes the job
     * at-least-once), and close.
     *
     * <p>The StreamLoad label names the first and last Kafka coordinates of the batch ({@code
     * prefix_subtask_firstPartition_firstOffset_lastPartition_lastOffset}). A batch replayed
     * after a restart with the same split points reuses its label, Doris answers "Label Already
     * Exists" for a FINISHED job and the client counts it as committed — batches that split
     * differently do get new labels and duplicate rows (new ids; see the class javadoc for the
     * --rebuild recommendation).
     *
     * <p>The {@code id} of each row comes from a per-subtask {@link AtomicLong}: seeded with a
     * time-based base ({@code currentTimeMillis() * 1000} plus the subtask index) and advanced by
     * the sink parallelism, so the subtasks' sequences never overlap, and a restart — which
     * re-seeds from a later clock reading — only ever produces ids larger than the pre-restart
     * ones (with UNIQUE KEY(id), a colliding id would overwrite a history row instead of
     * appending one).
     */
    public static class DorisStagingSink extends RichSinkFunction<StagedCanalRow>
            implements CheckpointedFunction {

        private static final long serialVersionUID = 1L;

        /** Label prefix of every StreamLoad this sink issues. */
        private static final String LABEL_PREFIX = "canal_staging";

        private final String fenodes;
        private final String username;
        private final String password;
        private final String database;
        private final String table;
        private final int batchSize;
        private final long flushIntervalNanos;

        private transient DorisHttpClient httpClient;
        private transient List<StagedCanalRow> buffer;
        private transient long lastFlushNanos;
        private transient int subtaskIndex;

        /** Assigns the {@code id} of every row this subtask writes. */
        private transient AtomicLong idCounter;

        /**
         * Step between two ids of this subtask (= the sink parallelism): subtask {@code i} owns
         * the sequence {@code base + i + n * parallelism}, so sequences never overlap.
         */
        private transient int idStride;

        public DorisStagingSink(
                String fenodes,
                String username,
                String password,
                String database,
                String table,
                int batchSize,
                long flushIntervalMs) {
            this.fenodes = fenodes;
            this.username = username;
            this.password = password;
            this.database = database;
            this.table = table;
            this.batchSize = batchSize;
            this.flushIntervalNanos = flushIntervalMs * 1_000_000L;
        }

        @Override
        public void open(Configuration parameters) {
            this.httpClient =
                    new DorisHttpClient(fenodes, username, password, DORIS_MAX_RETRIES);
            this.buffer = new ArrayList<>(Math.max(1, batchSize));
            this.lastFlushNanos = System.nanoTime();
            this.subtaskIndex = getRuntimeContext().getIndexOfThisSubtask();
            this.idStride = getRuntimeContext().getNumberOfParallelSubtasks();
            // * 1000 leaves headroom in one millisecond; only the base has to be "large and
            // forward-moving" for uniqueness across restarts — the counter itself is monotonic.
            long idBase = System.currentTimeMillis() * 1_000L;
            this.idCounter = new AtomicLong(idBase + subtaskIndex);
            LOG.info(
                    "Sink subtask {} generating ids from {} with stride {}",
                    subtaskIndex,
                    idCounter.get(),
                    idStride);
        }

        @Override
        public void invoke(StagedCanalRow row, Context context) throws IOException {
            buffer.add(row);
            if (buffer.size() >= batchSize
                    || System.nanoTime() - lastFlushNanos >= flushIntervalNanos) {
                flush();
            }
        }

        @Override
        public void snapshotState(FunctionSnapshotContext context) throws Exception {
            // Empty the buffer under the checkpoint barrier: recovery replays everything after
            // the last flushed row (and Doris deduplicates whole batches by label).
            flush();
        }

        @Override
        public void initializeState(FunctionInitializationContext context) throws Exception {
            // The sink keeps no state: the source's replay plus the StreamLoad labels carry the
            // at-least-once guarantee.
        }

        @Override
        public void close() throws IOException {
            try {
                flush();
            } finally {
                if (httpClient != null) {
                    httpClient.close();
                }
            }
        }

        private void flush() throws IOException {
            if (buffer.isEmpty()) {
                return;
            }
            StagedCanalRow first = buffer.get(0);
            StagedCanalRow last = buffer.get(buffer.size() - 1);
            // One topic per job, so partition+offset identify a position; the first and the last
            // position of the batch bound it, and the same bounds produce the same label.
            String label =
                    LABEL_PREFIX
                            + "_"
                            + subtaskIndex
                            + "_"
                            + first.kafkaPartition
                            + "_"
                            + first.kafkaOffset
                            + "__"
                            + last.kafkaPartition
                            + "_"
                            + last.kafkaOffset;
            List<Map<String, Object>> rows = new ArrayList<>(buffer.size());
            for (StagedCanalRow row : buffer) {
                Map<String, Object> dorisRow = toDorisRow(row);
                dorisRow.put(COL_ID, idCounter.getAndAdd(idStride));
                rows.add(dorisRow);
            }
            try {
                httpClient.streamLoad(database, table, label, rows);
            } catch (IOException e) {
                LOG.error(
                        "StreamLoad {} of {} rows into {}.{} failed; failing the subtask so the"
                                + " job recovers and replays the batch.",
                        label,
                        rows.size(),
                        database,
                        table,
                        e);
                throw e;
            }
            LOG.info(
                    "StreamLoad {} committed {} rows into {}.{}",
                    label,
                    rows.size(),
                    database,
                    table);
            buffer.clear();
            lastFlushNanos = System.nanoTime();
        }

        /**
         * Renders one staging row as a column-name to JSON-value map; the {@code id} is assigned
         * by the caller (see {@link #flush}). Every row carries the {@code __DORIS_DELETE_SIGN__}
         * marker the {@link DorisHttpClient#streamLoad} protocol declares ({@code false} = upsert).
         */
        private static Map<String, Object> toDorisRow(StagedCanalRow row) {
            Map<String, Object> values = new LinkedHashMap<>();
            values.put(COL_KAFKA_TOPIC, row.kafkaTopic);
            values.put(COL_KAFKA_PARTITION, row.kafkaPartition);
            values.put(COL_KAFKA_OFFSET, row.kafkaOffset);
            values.put(COL_CANAL_DATABASE, row.canalDatabase);
            values.put(COL_CANAL_TABLE, row.canalTable);
            values.put(COL_CANAL_TYPE, row.canalType);
            values.put(COL_CANAL_IS_DDL, row.canalIsDdl);
            values.put(COL_CANAL_ROW_COUNT, row.canalRowCount);
            values.put(COL_CANAL_ES, row.canalEs);
            values.put(COL_CANAL_TS, row.canalTs);
            values.put(COL_INGEST_TS, row.ingestTimestamp);
            values.put(COL_CANAL_JSON, row.canalJson);
            values.put(DorisHttpClient.DELETE_SIGN_COLUMN, false);
            return values;
        }
    }

