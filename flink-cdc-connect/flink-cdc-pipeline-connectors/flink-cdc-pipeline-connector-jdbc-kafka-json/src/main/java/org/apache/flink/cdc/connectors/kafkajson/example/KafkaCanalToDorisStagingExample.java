        /**
         * Parses {@code --key=value} options and boolean flags; prints usage and exits on error.
         */
        static Params parseOrExit(String[] args) {
            Map<String, String> options = new LinkedHashMap<>();
            boolean rebuild = false;
            boolean stopAtLatest = false;
            boolean help = false;
            for (String arg : args) {
                if ("--rebuild".equals(arg)) {
                    rebuild = true;
                } else if ("--stop-at-latest".equals(arg)) {
                    stopAtLatest = true;
                } else if ("--help".equals(arg) || "-h".equals(arg)) {
                    help = true;
                } else if (arg.startsWith("--") && arg.contains("=")) {
                    int separator = arg.indexOf('=');
                    options.put(arg.substring(2, separator), arg.substring(separator + 1));
                } else {
                    LOG.error("Unrecognized argument: " + arg);
                    usageAndExit();
                }
            }
            if (help) {
                usageAndExit(0);
            }
            String bootstrap = required(options, "kafka-bootstrap-servers");
            String topic = required(options, "kafka-topic");
            String fenodes = required(options, "doris-fenodes");
            String database = required(options, "doris-database");

            // Optional: no --table-filter (or "*") stages everything the topic carries.
            TableFilter tableFilter;
            try {
                tableFilter = TableFilter.parse(optional(options, "table-filter", "*"));
            } catch (IllegalArgumentException e) {
                LOG.error(e.getMessage());
                usageAndExit();
                return null; // unreachable
            }

            // Optional: where the source starts; earliest is the historical default.
            StartupMode startupMode =
                    parseStartupMode(optional(options, "startup-mode", "earliest"));

            // Timestamp startup position: required in timestamp mode, ignored otherwise (warned).
            String rawTimestamp = options.get("startup-timestamp");
            boolean hasTimestamp = rawTimestamp != null && !rawTimestamp.trim().isEmpty();
            long startupTimestampMillis = 0L;
            if (startupMode == StartupMode.TIMESTAMP) {
                if (!hasTimestamp) {
                    LOG.error(
                            "--startup-timestamp is required with"
                                    + " --startup-mode=timestamp (10 digits epoch seconds or"
                                    + " 13 digits epoch milliseconds)");
                    usageAndExit();
                }
                startupTimestampMillis = parseTimestampToMillis(rawTimestamp.trim());
            } else if (hasTimestamp) {
                LOG.warn("--startup-timestamp is ignored because --startup-mode is not"
                        + " timestamp but {}", startupMode);
            }

            int batchSize = intOption(options, "batch-size", DEFAULT_BATCH_SIZE);
            if (batchSize < 1) {
                LOG.error("--batch-size must be at least 1, got: " + batchSize);
                usageAndExit();
            }
            long flushIntervalMs =
                    longOption(options, "flush-interval-ms", DEFAULT_FLUSH_INTERVAL_MS);
            if (flushIntervalMs < 0) {
                LOG.error(
                        "--flush-interval-ms must not be negative, got: " + flushIntervalMs);
                usageAndExit();
            }
            String replicationAllocation =
                    optional(
                            options,
                            "doris-replication-allocation",
                            DEFAULT_DORIS_REPLICATION_ALLOCATION);

            return new Params(
                    bootstrap,
                    topic,
                    optional(options, "kafka-group-id", DEFAULT_KAFKA_GROUP_ID),
                    startupMode,
                    startupTimestampMillis,
                    stopAtLatest,
                    tableFilter,
                    fenodes,
                    optional(options, "doris-username", DEFAULT_DORIS_USERNAME),
                    optional(options, "doris-password", ""),
                    database,
                    optional(options, "doris-table", DEFAULT_DORIS_TABLE),
                    replicationAllocation,
                    rebuild,
                    batchSize,
                    flushIntervalMs);
        }

        private static StartupMode parseStartupMode(String value) {
            if ("earliest".equalsIgnoreCase(value.trim())) {
                return StartupMode.EARLIEST;
            }
            if ("latest".equalsIgnoreCase(value.trim())) {
                return StartupMode.LATEST;
            }
            if ("timestamp".equalsIgnoreCase(value.trim())) {
                return StartupMode.TIMESTAMP;
            }
            LOG.error(
                    "--startup-mode must be 'earliest', 'latest' or 'timestamp', got: " + value);
            usageAndExit();
            return null; // unreachable
        }

        /**
         * The timestamp digit convention: Kafka itself works in epoch <b>milliseconds</b>, so 13
         * digits pass through unchanged; 10 digits are accepted as epoch <b>seconds</b> (the unit
         * many business systems produce) and are converted. Any other length is rejected — the
         * digit count alone decides the unit, so an ambiguous value can never silently pick the
         * wrong scale.
         *
         * @throws NumberFormatException reported via usage-and-exit when the value is not numeric
         */
        private static long parseTimestampToMillis(String value) {
            long parsed;
            try {
                parsed = Long.parseLong(value);
            } catch (NumberFormatException e) {
                LOG.error("--startup-timestamp must be numeric, got: " + value);
                usageAndExit();
                return 0L; // unreachable
            }
            int digits = value.length();
            if (digits == 13) {
                return parsed; // epoch milliseconds, Kafka's native unit
            }
            if (digits == 10) {
                return parsed * 1_000L; // epoch seconds -> milliseconds
            }
            LOG.error(
                    "--startup-timestamp must be epoch seconds (10 digits, e.g. 1700000000) or"
                            + " epoch milliseconds (13 digits, e.g. 1700000000000), got: "
                            + value
                            + " ("
                            + digits
                            + " digits)");
            usageAndExit();
            return 0L; // unreachable
        }

        private static String required(Map<String, String> options, String key) {
            String value = options.get(key);
            if (value == null || value.trim().isEmpty()) {
                LOG.error("Missing required option --" + key);
                usageAndExit();
            }
            return value.trim();
        }

        private static String optional(
                Map<String, String> options, String key, String defaultValue) {
            String value = options.get(key);
            return value == null || value.trim().isEmpty() ? defaultValue : value.trim();
        }

        private static int intOption(Map<String, String> options, String key, int defaultValue) {
            String value = options.get(key);
            if (value == null || value.trim().isEmpty()) {
                return defaultValue;
            }
            try {
                return Integer.parseInt(value.trim());
            } catch (NumberFormatException e) {
                LOG.error("--" + key + " must be an integer, got: " + value);
                usageAndExit();
                return defaultValue; // unreachable
            }
        }

        private static long longOption(Map<String, String> options, String key, long defaultValue) {
            String value = options.get(key);
            if (value == null || value.trim().isEmpty()) {
                return defaultValue;
            }
            try {
                return Long.parseLong(value.trim());
            } catch (NumberFormatException e) {
                LOG.error("--" + key + " must be a long, got: " + value);
                usageAndExit();
                return defaultValue; // unreachable
            }
        }

