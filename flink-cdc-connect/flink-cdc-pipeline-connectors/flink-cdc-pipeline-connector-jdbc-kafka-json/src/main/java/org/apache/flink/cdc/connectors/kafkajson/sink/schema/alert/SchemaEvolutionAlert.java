package org.apache.flink.cdc.connectors.kafkajson.sink.schema.alert;

import org.apache.flink.cdc.common.annotation.PublicEvolving;
import org.apache.flink.cdc.common.event.TableId;

import javax.annotation.Nullable;

import java.io.Serializable;
import java.util.Objects;

/**
 * One schema-evolution alert emitted by a sink engine when it deliberately skipped a schema change
 * that Doris would have rejected.
 *
 * <p>Alerts are only produced for <b>non-idempotent</b> skips: an {@code ADD COLUMN} whose column
 * already exists is a duplicate that the applier resolves silently, while a {@code MODIFY COLUMN}
 * on a key column (or a rename whose source and target are both missing) would make Doris fail the
 * job, so the applier skips it and tells the user why. Every such skip leaves the Doris table
 * diverged from the source schema, which is why it is surfaced instead of only being logged.
 *
 * <p>{@link #getAlertId()} is deterministic for the same event, column and reason. It is stable
 * across job restarts, so a handler that forwards alerts to a system with at-least-once delivery
 * (or a user who runs the job through a failover) can deduplicate on it. Alerts generated by an
 * uncommitted schema-change round are re-delivered after a checkpoint restore; the duplicate
 * suppression here is intentionally left to the receiver because the applier has no durable state
 * of its own.
 */
@PublicEvolving
public final class SchemaEvolutionAlert implements Serializable {

    private static final long serialVersionUID = 1L;

    /**
     * How urgently the user should look at the alert.
     *
     * <p>{@link #INFO} is reserved for resolutions that are safe to repeat (a duplicate DDL that
     * was already applied) and is never delivered to a {@link SchemaEvolutionAlertHandler}. {@link
     * #WARNING} marks a non-idempotent skip that leaves the target schema diverged.
     */
    public enum Level {
        INFO,
        WARNING
    }

    /** The reason the applier skipped the change. Useful for routing/filtering on the receiver. */
    public enum Kind {
        /** The change was already applied; skipping it is idempotent. */
        DUPLICATE,
        /** A {@code MODIFY COLUMN} on a primary-key column; Doris rejects such changes. */
        MODIFY_KEY_COLUMN,
        /** A capacity reduction (for example a shorter VARCHAR); Doris rejects the narrowing. */
        CAPACITY_REDUCTION,
        /** The operation names a column that the Doris table does not have. */
        MISSING_COLUMN,
        /** The operation names a column that the Doris table already has. */
        COLUMN_CONFLICT,
        /** The operation targets a table that the Doris database does not have. */
        MISSING_TABLE,
        /** The Doris table is in a state the operation cannot be reconciled with. */
        INCONSISTENT_STATE
    }

    private final Level level;
    private final Kind kind;
    private final String alertId;
    private final TableId tableId;
    private final String eventType;
    @Nullable private final String column;
    private final String message;
    @Nullable private final String skippedSql;

    public SchemaEvolutionAlert(
            Level level,
            Kind kind,
            TableId tableId,
            String eventType,
            @Nullable String column,
            String message,
            @Nullable String skippedSql) {
        this.level = level;
        this.kind = kind;
        this.tableId = tableId;
        this.eventType = eventType;
        this.column = column;
        this.message = message;
        this.skippedSql = skippedSql;
        // Stable across restarts and JVMs: String.hashCode is specified by the JLS, and the other
        // parts identify the event/column/reason rather than the attempt.
        this.alertId =
                kind
                        + "|"
                        + tableId
                        + "|"
                        + eventType
                        + "|"
                        + (column == null ? "-" : column)
                        + "|"
                        + Integer.toHexString(message.hashCode());
    }

    public Level getLevel() {
        return level;
    }

    public Kind getKind() {
        return kind;
    }

    /**
     * Deterministic identity of this alert, stable across restarts. A handler with at-least-once
     * delivery can use it to deduplicate replayed alerts.
     */
    public String getAlertId() {
        return alertId;
    }

    /** The source table id (before database/table mapping). */
    public TableId getTableId() {
        return tableId;
    }

    /** Simple name of the schema-change event that triggered the alert. */
    public String getEventType() {
        return eventType;
    }

    /** The affected column, or {@code null} for table-level alerts. */
    @Nullable
    public String getColumn() {
        return column;
    }

    /** Human-readable explanation, suitable for logs and alert payloads. */
    public String getMessage() {
        return message;
    }

    /** The DDL that was deliberately not executed, or {@code null} when none was built. */
    @Nullable
    public String getSkippedSql() {
        return skippedSql;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof SchemaEvolutionAlert)) {
            return false;
        }
        SchemaEvolutionAlert that = (SchemaEvolutionAlert) o;
        return level == that.level
                && kind == that.kind
                && Objects.equals(alertId, that.alertId)
                && Objects.equals(tableId, that.tableId)
                && Objects.equals(eventType, that.eventType)
                && Objects.equals(column, that.column)
                && Objects.equals(message, that.message)
                && Objects.equals(skippedSql, that.skippedSql);
    }

    @Override
    public int hashCode() {
        return Objects.hash(level, kind, alertId, tableId, eventType, column, message, skippedSql);
    }

    @Override
    public String toString() {
        return "SchemaEvolutionAlert{"
                + "level="
                + level
                + ", kind="
                + kind
                + ", tableId="
                + tableId
                + ", eventType='"
                + eventType
                + '\''
                + ", column='"
                + column
                + '\''
                + ", message='"
                + message
                + '\''
                + '}';
    }
}
